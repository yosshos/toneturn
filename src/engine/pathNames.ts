/** The short road name of a lesson / topic; numbered lessons ("Rhythm 2: eighth notes") keep "Rhythm 2". */
export function shortName(id: string, full: L2, lang: 'en' | 'he'): string {
  const s = SHORT[id];
  if (s) return s[lang];
  const t = full[lang];
  const numbered = t.match(/^(.{2,16}?\s\d+):/);
  if (numbered) return numbered[1];
  return t.replace(/\s*\([^)]*\)\s*$/, '');
}

export const hasShortName = (id: string) => id in SHORT;

// Plain-language glossary (spec AC, deepened in 0.48 §L): every music word the app uses, explained in one or two
// clear sentences, with one line of real use and a sound. Mini-lessons show the words of each step as tappable chips;
// Practice → Lessons → Glossary lists them all.

import type { PercKind, Stimulus } from '../engine/lesson';
import { fxSpec, type FxChain, type FxSource } from '../engine/fx';
import { PROGRESSIONS, type JazzChord } from '../engine/jazz';
import type { Bi } from './miniTypes';

export interface Term {
  id: string;
  label: Bi;
  /** One or two plain sentences — no other jargon. */
  explain: Bi;
  /** One short line showing the term in real use. */
  example?: Bi;
  play: Stimulus[];
  /** What to look for in a sentence (English is matched case-insensitively). */
  match: { en: RegExp; he: RegExp };
}

const notes = (midis: number[], each = 0.4): Stimulus => ({ kind: 'notes', midis, each });
const chord = (midis: number[], duration = 1.3): Stimulus => ({ kind: 'chord', midis, duration });
const rest = (duration = 0.4): Stimulus => ({ kind: 'rest', duration });
const C = { letter: 'C' as const, acc: 0 as const };
const G = { letter: 'G' as const, acc: 0 as const };
const clicks = (n: number, gap: number): Stimulus => ({
  kind: 'events',
  events: Array.from({ length: n }, (_, i) => ({ midi: 76, start: i * gap, duration: 0.05, velocity: i % 4 === 0 ? 0.7 : 0.45, perc: i % 4 === 0 ? ('accent' as const) : ('click' as const) })),
  length: n * gap + 0.2,
});
/** Clicks grouped as a meter: `true` = an accented beat (the first of the bar is the strongest). */
const pulse = (accents: boolean[], gap: number, reps = 2): Stimulus => {
  const all = Array.from({ length: reps }, () => accents).flat();
  return {
    kind: 'events',
    events: all.map((a, i) => ({ midi: 76, start: i * gap, duration: 0.05, velocity: i % accents.length === 0 ? 0.8 : a ? 0.6 : 0.35, perc: a ? ('accent' as const) : ('click' as const) })),
    length: all.length * gap + 0.2,
  };
};
type Ev = [midi: number, start: number, duration: number, velocity?: number, perc?: PercKind];
/** Free timed notes or drums. */
const ev = (list: Ev[], length: number): Stimulus => ({
  kind: 'events',
  events: list.map(([midi, start, duration, velocity = 0.6, perc]) => ({ midi, start, duration, velocity, ...(perc ? { perc } : {}) })),
  length,
});
/** The same notes in a row, with their own loudness and length. */
const line = (midis: number[], gap: number, dur: number, vel: number | number[] = 0.6): Stimulus =>
  ev(midis.map((m, i) => [m, i * gap, dur, Array.isArray(vel) ? vel[i] : vel] as Ev), midis.length * gap + 0.3);
const phrase = (chords: ('I' | 'ii' | 'iii' | 'IV' | 'V' | 'V7' | 'vi')[]): Stimulus => ({ kind: 'phrase', key: C, chords });
const R = (rhythm: string, bpm: number, bars = 1): Stimulus => ({ kind: 'rhythm', rhythm, bars, bpm });
const jazz = (chords: JazzChord[], each = 1.1): Stimulus => ({ kind: 'jazz', key: C, chords, each });
const SRC: Record<FxSource, number> = { pink: 2, loop: 4, drums: 4, voice: 3, sine: 1.4 };
/** A processed sound, loudness-matched to the plain one unless `level`. */
const fx = (source: FxSource, chain: FxChain, extra: { sineHz?: number; level?: boolean } = {}): Stimulus => ({
  kind: 'fx',
  fx: fxSpec({ source, seed: 4242, bpm: 120, src: SRC[source], chain, ...(extra.sineHz ? { sineHz: extra.sineHz } : {}), ...(extra.level ? {} : { matchTo: {} }) }),
});
/** Hebrew has no \b — a word edge is anything that is not a Hebrew letter. */
const heWord = (body: string) => new RegExp(`(^|[^\\u05D0-\\u05EA])(?:[ובלהמש]{0,2})(?:${body})(?=$|[^\\u05D0-\\u05EA])`);
/** Skip words like "the third step / the fifth note", where the ordinal is not an interval. */
const NOT_ORDINAL = '(?! (?:step|degree|note|beat|bar|string|finger|fret|time|inversion|chord|line|space)s?\\b)';


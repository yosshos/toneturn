// Prints the SQL that seeds the server's daily-challenge answer keys (spec I, async daily leaderboard).
// The daily set is deterministic per day (src/engine/tournament.ts, DAILY_VERSION); if the generator
// changes, bump DAILY_VERSION and re-seed. Usage: npm run daily-keys > supabase/seed/daily_keys.sql
import { DAILY_VERSION, dailySet } from '../src/engine/tournament';

const from = new Date(Date.UTC(2026, 10, 1));
const to = new Date(Date.UTC(2028, 11, 31));
const rows: string[] = [];
for (let d = from; d <= to; d = new Date(d.getTime() + 86_400_000)) {
  const day = d.toISOString().slice(0, 10);
  const keys = dailySet(day).map((q) => `'${String(q.answer).replace(/'/g, "''")}'`);
  rows.push(`('${day}', ${DAILY_VERSION}, array[${keys.join(',')}])`);
}
console.log(`-- Generated by scripts/daily-keys.ts (DAILY_VERSION ${DAILY_VERSION}). Do not edit by hand.`);
console.log('insert into public.toneturn_daily_keys (day, version, answers) values');
console.log(rows.join(',\n'));
console.log('on conflict (day) do update set version = excluded.version, answers = excluded.answers;');

// Prints the SQL that seeds the server's daily-challenge answer keys (spec I, async daily leaderboard).
// The daily set is deterministic per day and band (src/engine/tournament.ts, DAILY_VERSION); if the generator
// changes, bump DAILY_VERSION and re-seed. Usage: npm run daily-keys > supabase/seed/daily_keys.sql
// Bands (GAMES_TIERS_PLAN, migration 20261128000000_toneturn_game_tiers.sql): soft (the original set), mid, loud.
// Needs the migration applied first (the band column and the (day, band) key).
import { DAILY_VERSION, dailySet } from '../src/engine/tournament';
import { DAILY_BANDS } from '../src/engine/gameTiers';

const from = new Date(Date.UTC(2026, 10, 1));
const to = new Date(Date.UTC(2031, 11, 31));
const rows: string[] = [];
for (let d = from; d <= to; d = new Date(d.getTime() + 86_400_000)) {
  const day = d.toISOString().slice(0, 10);
  for (const band of DAILY_BANDS) {
    const keys = dailySet(day, band).map((q) => `'${String(q.answer).replace(/'/g, "''")}'`);
    rows.push(`('${day}', '${band}', ${DAILY_VERSION}, array[${keys.join(',')}])`);
  }
}
console.log(`-- Generated by scripts/daily-keys.ts (DAILY_VERSION ${DAILY_VERSION}). Do not edit by hand.`);
console.log('insert into public.toneturn_daily_keys (day, band, version, answers) values');
console.log(rows.join(',\n'));
console.log('on conflict (day, band) do update set version = excluded.version, answers = excluded.answers;');

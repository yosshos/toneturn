import { chromium } from '@playwright/test';
const out = process.argv[2];
const b = await chromium.launch({ channel: 'chrome' });
const p = await b.newPage({ viewport: { width: 390, height: 844 } });
p.on('pageerror', (e) => console.log('PAGEERR', e.message.slice(0, 300)));
await p.goto('http://localhost:5173/?sim=1&unlock=all&lang=he#/path');
await p.waitForTimeout(1500);
await p.getByRole('button', { name: /3\. מז׳ור או מינור|מז׳ור או מינור/ }).first().click().catch(() => console.log('no lesson btn'));
await p.waitForTimeout(800);
await p.getByRole('button', { name: /קול|להשתמש בקול/ }).first().click().catch(() => {});
await p.locator('main.recap').waitFor({ timeout: 150000 }).catch(() => console.log('no recap'));
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/recap-1.png` });
await p.locator('[data-recap-next]').click().catch(() => {});
await p.waitForTimeout(900);
await p.screenshot({ path: `${out}/recap-2.png` });
await p.locator('[data-recap-next]').click().catch(() => {});
await p.waitForTimeout(900);
await p.screenshot({ path: `${out}/recap-3.png` });
await b.close();
